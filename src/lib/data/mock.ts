interface ProductInput {
  sku: string;
  name: string;
  brand: string;
  category: string;
  subcategory?: string;
  unit: string;
  pack?: string;
  price: number;
  wholesale?: [price: number, minQty: number];
  list?: number;
  pix?: number;
  imgs: ImgKey[];
  rating?: number;
  reviews?: number;
  badges?: ProductBadge[];
  short: string;
  description?: string;
  specs?: [string, string][];
  supplier: string;
  stock?: StockStatus;
  tags?: string[];
  yieldHint?: string;
}

let seq = 0;

function product(p: ProductInput): Product {
  seq += 1;
  const id = `prd-${String(seq).padStart(4, "0")}`;
  return {
    id,
    slug: slugify(p.name),
    sku: p.sku,
    name: p.name,
    brand: p.brand,
    brandSlug: slugify(p.brand),
    categorySlug: p.category,
    subcategorySlug: p.subcategory,
    unit: p.unit,
    packInfo: p.pack,
    retailPrice: p.price,
    wholesalePrice: p.wholesale?.[0],
    wholesaleMinQty: p.wholesale?.[1],
    listPrice: p.list,
    pixDiscountPct: p.pix,
    images: p.imgs.map((k) => img(k)),
    rating: p.rating ?? 4.6,
    reviewCount: p.reviews ?? 0,
    badges: p.badges ?? [],
    shortDescription: p.short,
    description: p.description,
    specs: p.specs?.map(([label, value]) => ({ label, value })),
    supplier: supplierById[p.supplier],
    stockStatus: p.stock ?? "supplier",
    tags: p.tags,
    yieldHint: p.yieldHint,
  };
}

